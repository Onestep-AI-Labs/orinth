def test_every_template_generates_code():
    for template_id, template in TEMPLATES.items():
        code = render(template.graph, name=template.name, num_classes=3)
        assert "def build_model(" in code, template_id


# The LLM scale presets are blueprints, not local builds — instantiating the
# 70B one would allocate hundreds of gigabytes. Their parameter arithmetic is
# verified analytically in `test_architecture_torch_and_presets.py`; this file
# builds only the templates a workstation can actually hold.
#
# Derived from the preset registry rather than an id prefix: a prefix rule
# missed the named model presets when they landed, and the whole suite OOMed.
BUILDABLE_TEMPLATES = [
    template_id
    for template_id in TEMPLATES
    if template_id not in PRESETS_BY_ID or template_id == "llm_tiny"
]


# --- real TensorFlow builds ------------------------------------------------


@pytest.mark.slow
@pytest.mark.parametrize("template_id", sorted(BUILDABLE_TEMPLATES))
def test_templates_build_under_tensorflow_and_match_the_analytic_pass(
    template_id, tmp_path, build_generated
):
    """The check that keeps `shapes.py` honest.

    Every predicted shape must equal the layer's real output shape, and where
    the parameter estimate is not `None` it must match exactly — an estimate
    that is merely close would hide an arithmetic bug.
    """

    template = TEMPLATES[template_id]
    graph = template.graph.model_copy(deep=True)
    for graph_node in graph.nodes:
        # Build offline: random initialization rather than an ImageNet download.
        if graph_node.type == "pretrained_backbone":
            graph_node.params["weights"] = "none"

    resolved = build_graph(graph)
    shapes, estimate, issues = infer_shapes(resolved, num_classes=3)
    assert not [issue for issue in (*resolved.issues, *issues) if issue.severity == "error"]

    code = emit_module(resolved, shapes, architecture_name=template.name, default_num_classes=3)
    model = build_generated(code, tmp_path, f"generated_{template_id}", num_classes=3)

    # The model's output must match what the analytic pass predicted for the
    # node feeding Output. Asserting `== num_classes` instead would be wrong
    # for any head with a fixed width — an LM head pinned to its own vocabulary
    # does not resize with the dataset, and should not.
    final = resolved.nodes[resolved.output_ids[0]].inputs[0]
    assert model.output_shape[1:] == tuple(shapes[final])
    if estimate is not None:
        assert model.count_params() == estimate

    for node_id in resolved.order:
        predicted = shapes.get(node_id)
        if predicted is None:
            continue
        try:
            layer = model.get_layer(resolved.nodes[node_id].var_name)
        except ValueError:
            # Output nodes and the backbone emit no layer under their own name.
            continue
        assert tuple(layer.output.shape[1:]) == tuple(predicted), node_id


@pytest.mark.slow
def test_generated_module_trains_for_one_step(tmp_path, build_generated):
    """End-to-end proof that a graph-built model is a normal trainable Keras model."""

    import numpy as np

    model = build_generated(render(tiny_cnn(), num_classes=2), tmp_path, "generated_tiny", 2)
    model.compile(optimizer="adam", loss="categorical_crossentropy", metrics=["accuracy"])

    history = model.fit(
        np.random.rand(8, 8, 8, 3).astype("float32"),
        np.eye(2, dtype="float32")[np.random.randint(0, 2, 8)],
        epochs=1,
        verbose=0,
    )

    assert "loss" in history.history
